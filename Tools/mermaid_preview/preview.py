"""Mermaid preview: the note of every diagram type, and a render check with the vault theme.

Usage (from WSL, any folder):
    python3 preview.py note             # rewrite _Meta/Mermaid Preview.md from samples.py
    python3 preview.py render [N,M]     # render samples in headless Edge with Obsidian's own Mermaid
                                        # and the vault snippets; one PNG per sample in out_dir

render takes mermaid.min.js out of Obsidian's app archive (same version as the app), builds one
page per sample with the palette of popping-and-locking.css + mermaid-afterglow.css, and renders
it the way Obsidian does (inside a hidden div.mermaid, Obsidian's mermaid.initialize settings).
Paths: "mermaid_preview" in LLM/vault_config.json. Use it after changing a colour or a snippet,
or after porting a theme, then look at the PNGs.
"""
import glob, html, json, struct, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VAULT = HERE.parents[1]
sys.path.insert(0, str(HERE))
from samples import SAMPLES

CFG = json.loads((VAULT / 'LLM' / 'vault_config.json').read_text(encoding='utf-8')).get('mermaid_preview', {})
SNIP = VAULT / '.obsidian' / 'snippets'
NOTE = VAULT / '_Meta' / 'Mermaid Preview.md'
SERIES = [('c1', '#6C99BB', 'blue'), ('c2', '#E5B567', 'yellow'), ('c3', '#B05279', 'magenta'), ('c4', '#A8C373', 'green'),
          ('c5', '#7DD6CF', 'cyan'), ('c6', '#FE8019', 'orange'), ('c7', '#9E86C8', 'purple'), ('c8', '#D3869B', 'pink')]
DOCS = {'Flowchart': 'flowchart', 'Flowchart 11.x features': 'flowchart', 'Sequence': 'sequenceDiagram',
        'Class': 'classDiagram', 'State': 'stateDiagram', 'Entity relationship': 'entityRelationshipDiagram',
        'User journey': 'userJourney', 'Gantt': 'gantt', 'Pie': 'pie', 'Quadrant': 'quadrantChart',
        'Requirement': 'requirementDiagram', 'Git graph': 'gitgraph', 'C4 context': 'c4', 'Mindmap': 'mindmap',
        'Timeline': 'timeline', 'Sankey': 'sankey', 'XY chart': 'xyChart', 'Block': 'block', 'Packet': 'packet',
        'Kanban': 'kanban', 'Architecture': 'architecture', 'Radar': 'radar', 'Treemap': 'treemap'}
INIT = ('{startOnLoad:false,securityLevel:"strict",themeVariables:{fontFamily:"var(--font-mermaid)"},'
        'flowchart:{useMaxWidth:false},sequence:{useMaxWidth:false},gantt:{useMaxWidth:true},journey:{useMaxWidth:true},'
        'class:{useMaxWidth:true},git:{useMaxWidth:false},state:{useMaxWidth:true},er:{useMaxWidth:false},pie:{useMaxWidth:true}}')


def note():
    chip = lambda v, c, n: (f'<span style="display:inline-block;margin:2px 10px 2px 0;font-family:monospace;font-size:12px;">'
                            f'<span style="display:inline-block;width:14px;height:14px;border-radius:3px;background:{c};'
                            f'vertical-align:middle;margin-right:4px;"></span>--diagram-{v} {c} {n}</span>')
    out = ['---', 'up: "[[_Meta]]"', 'sticker: lucide//workflow', 'tags:', '  - theme', '  - reference', '---',
           '# Mermaid Preview', '',
           'Every Mermaid diagram type that Obsidian renders, drawn live with the vault theme. Colours come from '
           '`mermaid-afterglow.css`, which uses only the variables of `popping-and-locking.css` (Style Settings → '
           'Popping and Locking → Diagram Colors). How to choose and write a diagram: skill `mermaid-diagrams`. '
           'Colour swatches: [[Theme Color Preview]]. Generated by `Tools/mermaid_preview/preview.py note`.', '',
           '> [!info] Version',
           '> Obsidian 1.14.5 bundles **Mermaid 11.13.0**. The [syntax docs](https://mermaid.ai/open-source/syntax/flowchart.html) '
           'describe newer versions: collapsible subgraphs (11.17) and the v12 defaults (ELK layout, `neo` look) do not '
           'render here yet. Expanded shapes (`A@{ shape: … }`, 11.3), edge animation and per-edge curves (11.10) do.', '',
           '## Colours', '',
           '> [!abstract] Diagram colours',
           '> - **Nodes**: fill `--background-primary-alt`, border `--diagram-node-border`, text `--diagram-text`; edges '
           '`--diagram-edge-color`; groups `--diagram-subgraph-border` (dashed).',
           '> - **Notes and edge labels**: light chip `--diagram-note-bg` with `--diagram-note-text`, border `--diagram-note-border`.',
           '> - **Semantic classes** (no `classDef` needed): `:::pass` `--diagram-success`, `:::fail` `--diagram-error`, '
           '`:::warn` `--diagram-warn`, `:::info` `--diagram-info`, `:::muted` faint dashed.',
           '> - **Series** (pie slices, chart bars and lines, gantt / journey / timeline / mindmap sections, radar curves, '
           'sankey nodes), in this order:', '>', '> ' + ''.join(chip(*x) for x in SERIES), '']
    for n, (t, desc, code) in enumerate(SAMPLES, 1):
        out += [f'## {n}. {t}', '', f'*{desc}* · [syntax](https://mermaid.ai/open-source/syntax/{DOCS.get(t, "flowchart")}.html)',
                '', '```mermaid', code, '```', '', '> [!example]- Source', '> ```text']
        out += ['> ' + l for l in code.split('\n')] + ['> ```', '']
    NOTE.write_text('\n'.join(out), encoding='utf-8')
    print(f'{NOTE.relative_to(VAULT)}: {len(SAMPLES)} diagrams')


def mermaid_js(dst):
    """Copy lib/mermaid.min.js out of the newest Obsidian app archive (asar: pickle header + JSON index)."""
    asar = sorted(glob.glob(CFG['obsidian_asar_glob']))[-1]
    with open(asar, 'rb') as f:
        head = f.read(16)
        index = json.loads(f.read(struct.unpack('<I', head[12:16])[0]))
        base = 8 + struct.unpack('<I', head[4:8])[0]
        entry = index['files']['lib']['files']['mermaid.min.js']
        f.seek(base + int(entry['offset']))
        dst.write_bytes(f.read(entry['size']))
    return Path(asar).name


def render(only):
    out = Path(CFG['out_dir'])
    out.mkdir(parents=True, exist_ok=True)
    print('mermaid from', mermaid_js(out / 'mermaid.min.js'))
    pal = (SNIP / 'popping-and-locking.css').read_text(encoding='utf-8')
    i = pal.index('1. PALETTE')
    palette = pal[pal.rfind('/*', 0, i):pal.rfind('/*', 0, pal.index('   2.', i))]
    css = palette + (SNIP / 'mermaid-afterglow.css').read_text(encoding='utf-8') + (
        'body{margin:0;padding:16px;background:var(--background-primary);color:var(--text-normal);'
        'font-family:"Segoe UI",sans-serif;--font-mermaid:"Segoe UI",sans-serif}'
        'h3{margin:0 0 8px;font-size:15px;color:var(--text-muted)}.mermaid svg{max-width:100%;height:auto}')
    winpath = lambda p: subprocess.run(['wslpath', '-w', str(p)], capture_output=True, text=True).stdout.strip()
    for n, (t, _, code) in enumerate(SAMPLES, 1):
        if only and n not in only:
            continue
        page = out / f'p{n:02d}.html'
        page.write_text(
            f'<!doctype html><html><head><meta charset="utf-8"><style>{css}</style><script src="mermaid.min.js"></script>'
            f'</head><body class="theme-dark"><h3>{n}. {html.escape(t)}</h3><div id="slot"></div>'
            f'<script id="src" type="text/plain">{html.escape(code)}</script><script>mermaid.initialize({INIT});'
            '(async()=>{const tmp=document.createElement("div");tmp.className="mermaid";'
            'tmp.style.cssText="width:1000px;visibility:hidden;position:absolute";document.body.appendChild(tmp);'
            'const slot=document.getElementById("slot");try{const r=await mermaid.render("m",'
            'new DOMParser().parseFromString(document.getElementById("src").textContent,"text/html").documentElement.textContent,tmp);'
            'slot.className="mermaid";slot.innerHTML=r.svg;}catch(e){slot.textContent="ERROR "+e;}tmp.remove();})();'
            '</script></body></html>', encoding='utf-8')
        png = out / f'p{n:02d}.png'
        subprocess.run([CFG['edge'], '--headless=new', '--disable-gpu', '--hide-scrollbars', '--allow-file-access-from-files',
                        '--virtual-time-budget=15000', f'--screenshot={winpath(png)}', '--window-size=1100,900',
                        'file:///' + winpath(page).replace('\\', '/')], capture_output=True, timeout=120)
        print(n, t, 'ok' if png.exists() else 'NO PNG')
    print('PNGs in', out)


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'note':
        note()
    elif cmd == 'render':
        render({int(x) for x in sys.argv[2].split(',')} if len(sys.argv) > 2 else None)
    else:
        sys.exit(__doc__)
